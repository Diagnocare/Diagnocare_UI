'use strict';

/**
 * Generates plan/storyboard.md from the recorder script.
 *
 * The storyboard is derived rather than written so it cannot fall out of step with what
 * is actually recorded: the narration here IS the narration in the video, read out of
 * the same module. When out/timeline.json exists, the measured durations are used in
 * place of the planned ones.
 */

const fs = require('node:fs');
const path = require('node:path');
const { sections } = require('../recorder/steps.js');

const ROOT = path.join(__dirname, '..');

function readTimeline() {
  const p = path.join(ROOT, 'out', 'timeline.json');
  if (!fs.existsSync(p)) return null;
  try { return JSON.parse(fs.readFileSync(p, 'utf8')); } catch { return null; }
}

function mmss(seconds) {
  const m = Math.floor(seconds / 60);
  const s = Math.round(seconds % 60);
  return `${m}:${String(s).padStart(2, '0')}`;
}

/**
 * The narration of a section, by running its `run` against a recording driver stub that
 * collects say() calls instead of performing them. Everything else is a no-op, and any
 * locator call is absorbed by a Proxy, so no browser is needed.
 */
async function narrationOf(section) {
  const lines = [];
  const noop = async () => {};

  // say() and titleCard() collect; everything else is absorbed. Any locator expression
  // resolves to a Proxy that is callable and has every property, so no browser is needed.
  const driver = new Proxy({
    say: async (en, hi) => { lines.push([en, hi]); },
    titleCard: async ({ narration = [] } = {}) => { for (const l of narration) lines.push(l); },
    centerOf: async () => ({ x: 0, y: 0, box: { x: 0, y: 0, width: 1, height: 1 } }),
  }, { get: (t, k) => (k in t ? t[k] : noop) });

  const anything = new Proxy(function () {}, {
    get: (_t, k) => {
      // Awaiting the proxy must not treat it as a thenable, or the await never settles.
      if (k === 'then') return undefined;
      // Counts and visibility checks are asked for in conditionals; answer truthily.
      if (k === 'count') return async () => 1;
      if (k === 'isVisible' || k === 'isEnabled') return async () => true;
      return anything;
    },
    apply: () => anything,
  });

  try {
    // A chapter that genuinely needs a live page stalls; whatever it narrated is kept.
    await Promise.race([
      section.run(driver, anything),
      new Promise(resolve => setTimeout(resolve, 2000)),
    ]);
  } catch { /* same */ }
  return lines;
}

async function main() {
  const timeline = readTimeline();
  const measured = new Map((timeline?.sections ?? []).map(s => [s.id, (s.endMs - s.startMs) / 1000]));

  const out = [];
  out.push('# Phase 3 — Tutorial storyboard');
  out.push('');
  out.push('> Generated by `npm run storyboard` from `recorder/steps.js`. Do not edit by hand —');
  out.push('> the narration below is read out of the recorder, so it is always what the video says.');
  out.push('');

  const total = sections.reduce(
    (sum, s) => sum + (measured.get(s.id) ?? s.meta.seconds), 0);
  out.push(`**${sections.length} chapters · ${mmss(total)} total**`
    + (timeline ? ' _(measured from the last recording)_' : ' _(planned)_'));
  out.push('');
  out.push('| # | Chapter | अध्याय | Length |');
  out.push('|---|---------|--------|--------|');
  sections.forEach((s, i) => {
    out.push(`| ${i + 1} | ${s.title} | ${s.titleHi} | ${mmss(measured.get(s.id) ?? s.meta.seconds)} |`);
  });
  out.push('');

  for (const [i, s] of sections.entries()) {
    out.push(`## ${i + 1}. ${s.title} — ${s.titleHi}`);
    out.push('');
    out.push(`- **Approximate duration:** ${mmss(measured.get(s.id) ?? s.meta.seconds)}`);
    out.push(`- **What appears on screen:** ${s.meta.onScreen}`);
    out.push(`- **What is clicked:** ${s.meta.clicks}`);
    out.push(`- **What is highlighted:** ${s.meta.highlight}`);
    out.push(`- **Expected result:** ${s.meta.expect}`);
    out.push('');
    out.push('**Narration**');
    out.push('');
    const lines = await narrationOf(s);
    if (!lines.length) {
      out.push('_(this chapter\'s narration is interleaved with live UI steps; see `recorder/steps.js`)_');
    }
    for (const [en, hi] of lines) {
      out.push(`> ${en}`);
      if (hi) out.push(`> <br>**हिन्दी:** ${hi}`);
      out.push('>');
    }
    out.push('');
  }

  const dest = path.join(ROOT, 'plan', 'storyboard.md');
  fs.writeFileSync(dest, `${out.join('\n')}\n`, 'utf8');
  process.stdout.write(`storyboard written to plan/storyboard.md (${sections.length} chapters)\n`);
}

main();
